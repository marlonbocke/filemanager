<?php 
if ($_SERVER['REQUEST_METHOD'] !== 'POST') {
    http_response_code(403);
    exit('Forbidden');
}

if(!isset($_POST['ip']) || !isset($_POST['port']) || !isset($_POST['user']) || !isset($_POST['password']) || !isset($_POST['db_name'])) 
{
    echo "<script>alert('Please try again'); window.location.href = 'index.html';</script>";
    exit;
} 

$ip = $_POST['ip'];
$port = $_POST['port'];
$user = $_POST['user'];
$password = $_POST['password'];
$db_name = $_POST['db_name'];

$file ='config/config.json';
$jsondata = file_get_contents($file);
$config = json_decode($jsondata, true); 



if (!is_array($config)) {
        $config = [];
        $file = 'config.json';
        file_put_contents($file, json_encode([]));  //generated by Google AI
    }
 

$config[0] = 
[
    "ip_address" => $ip,
    "port" => $port,
    "username" => $user,
    "password" => $password,
    "databasename" => $db_name,

];

$saved=file_put_contents($file, json_encode($config, JSON_PRETTY_PRINT | JSON_UNESCAPED_UNICODE));

if ($saved) {
    echo "<script>alert('Config saved'); window.location.href = '/filemanager_new/index.php';</script>";
} else {
    echo "<script>alert('Config haven't been saved. Please try again')</script>";
    return;
}